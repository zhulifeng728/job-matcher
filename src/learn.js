/**
 * learn.js —— 技能缺口的学习路径
 *
 * 为什么需要这个：
 * 只告诉用户「JD 要求微前端但你没有」是没用的 —— 他知道缺，但不知道
 * 该学什么、学到什么程度算会、面试怎么讲。这句话不产生任何行动。
 *
 * 所以每个缺口都给出四件事：
 *   1. 这是什么（一句话）
 *   2. 最小学习路径（2-4 步，能动手的）
 *   3. 判断标准（能回答什么问题算学会）
 *   4. 没实践过时怎么说（诚实且不吃亏的表达）
 *
 * 学会之后由用户自己确认，才会进入简历技能区 —— 系统不替用户撒谎。
 */

