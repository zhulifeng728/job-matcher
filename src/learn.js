/** 找不到专门知识时的通用模板 */
function genericPlan(term, category) {
  const byCat = {
    tool: {
      steps: [
        `在官方文档跑通 ${term} 的最小示例`,
        `用它做一个小功能，能说清它解决了什么问题`,
        `对比一个你熟悉的同类方案，说清取舍`,
      ],
      check: [`${term} 解决什么问题？`, `为什么用它而不是你熟悉的那套？`, `它的边界在哪？`],
      hours: 8,
    },
    method: {
      steps: [
        `先想清 ${term} 解决的具体痛点是什么（不要说「提升效率」这种空话）`,
        `在现有项目里找一处能套用的场景，真正做一次`,
        `记录改造前后差在哪 —— 面试时这段比概念重要得多`,
      ],
      check: [`你实际怎么做 ${term} 的？举一个具体例子。`, `${term} 做到什么程度算好？`],
      hours: 6,
    },
    domain: {
      steps: [
        `了解 ${term} 行业的典型业务流`,
        `找 2-3 个该行业的招聘 JD，看反复出现的要求`,
        `把已有经历里能迁移的部分想清楚`,
      ],
      check: [`${term} 业务的前端难点在哪？`],
      hours: 6,
    },
    duty: {
      steps: [
        `把 ${term} 拆成 2-3 个具体动作`,
        `在过往经历里找一件能证明它的事，按「背景-动作-结果」写下来`,
      ],
      check: [`你具体怎么做 ${term} 的？举一个真实例子。`],
      hours: 4,
    },
  };
  const c = byCat[category] || byCat.tool;
  return {
    what: `${term}（JD 提到这个要求，你的简历里还没有对应证据）`,
    steps: c.steps,
    check: c.check,
    honest: `如果只是了解没实践过，可以说：「${term} 我了解概念和大致做法，还没在项目里深度用过，`
      + '但和我做过的 X 比较接近，上手应该很快。」',
    hours: c.hours,
  };
}

/**
 * 为缺失的关键词生成学习计划
 * @param {Array<{term, category}>} gaps
 */
export function buildLearningPlan(gaps = []) {
  return gaps.map((g) => {
    const plan = PLANS[g.term] || genericPlan(g.term, g.category);
    return {
      term: g.term,
      category: g.category,
      what: plan.what,
      steps: plan.steps,
      check: plan.check,
      honest: plan.honest,
      hours: plan.hours,
      // 是否已经有现成的详细路径（否则是通用模板）
      detailed: Boolean(PLANS[g.term]),
    };
  });
}

/** 汇总：需要多少时间 */
export function summarizePlan(plan = []) {
  const totalHours = plan.reduce((s, p) => s + (p.hours || 0), 0);
  const detailed = plan.filter((p) => p.detailed).length;
  return {
    count: plan.length,
    totalHours,
    // 按每天 3 小时投入估算
    days: Math.ceil(totalHours / 3),
    detailed,
    note: totalHours > 40
      ? '缺口比较多。建议先补 P0（最常被问的 2-3 个），剩下的用「诚实表达」过渡。'
      : '工作量可控，按顺序补完就能覆盖这个岗位的主要要求。',
  };
}
